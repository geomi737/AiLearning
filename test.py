import numpy as np

# Допустим, у нас батч из 2 картинок, 1 канал, размер 3x3 (чисто для теста)
x = np.ones((2, 1, 3, 3)) 
print(x)

# Задаем отступы для каждой из 4-х осей: (до, после)
# Для 0-й оси (батч) — 0 нулей до, 0 после
# Для 1-й оси (каналы) — 0 нулей до, 0 после
# Для 2-й оси (высота) — 1 ноль сверху, 1 ноль снизу
# Для 3-й оси (ширина) — 1 ноль слева, 1 ноль справа
padding_config = ((0, 0), (0, 0), (1, 1), (1, 1))

# Навешиваем паддинг
x_padded = np.pad(x, pad_width=padding_config, mode='constant', constant_values=0)

print(x_padded)

print("Было:", x.shape)         # Выведет: (2, 1, 3, 3)
print("Стало:", x_padded.shape)  # Выведет: (2, 1, 5, 5) — рамка из нулей добавилась!